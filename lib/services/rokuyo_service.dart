  /// 六曜名リスト
  static const List<String> _rokuyoList = [
    '先勝', '友引', '先負', '仏滅', '大安', '赤口'
  ];

  /// グレゴリオ暦から六曜名を取得（メインAPI）
  static String getRokuyo(DateTime date) {
    final lunar = _toLunar(date);
    final index = _getRokuyoIndex(lunar[0], lunar[1]);
    return _rokuyoList[index];
  }

  /// 六曜インデックスを取得
  /// 計算式: (旧暦月 + 旧暦日 - 2) % 6
  /// 旧暦1月1日=先勝(0), 2月1日=友引(1), 3月1日=先負(2), ...
  static int _getRokuyoIndex(int lunarMonth, int lunarDay) {
    return ((lunarMonth + lunarDay - 2) % 6 + 6) % 6;
  }

  /// 後方互換のためのパブリック版
  static int getRokuyoIndex(int lunarMonth, int lunarDay) {
    return _getRokuyoIndex(lunarMonth, lunarDay);
  }

  /// 六曜の色インデックスを返す（表示用）
  static int getRokuyoColorIndex(String rokuyo) {
    return rokuyoNames.indexOf(rokuyo);
  }

  /// グレゴリオ暦から旧暦[月, 日]を取得
  /// 戻り値: [旧暦月番号(1-12), 旧暦日(1-30)]
  static List<int> _toLunar(DateTime date) {
    final jd = _toJulianDay(date.year, date.month, date.day);
    return _julianToLunar(jd, date.year);
  }

  /// グレゴリオ暦からユリウス日を計算
  static double _toJulianDay(int year, int month, int day) {
    int y = year;
    int m = month;
    int d = day;
    if (m < 3) {
      y -= 1;
      m += 12;
    }
    final int a = (y / 100).floor();
    final int b = 2 - a + (a / 4).floor();
    return (365.25 * (y + 4716)).floor() +
        (30.6001 * (m + 1)).floor() +
        d +
        b -
        1524.5;
  }

  /// ユリウス日から旧暦[月, 日]を計算
  /// 精密な朔日テーブルを使用するため正確
  static List<int> _julianToLunar(double jd, int year) {
    // 当年・前年の順でテーブル検索
    for (int tryYear in [year, year - 1]) {
      final result = _lookupLunarFromTable(jd, tryYear);
      if (result != null) return result;
    }
    // フォールバック（テーブル範囲外）
    return [1, 1];
  }

  /// 指定年のテーブルからJDに対応する旧暦[月, 日]を検索
  static List<int>? _lookupLunarFromTable(double jd, int year) {
    final yearData = _lunarMonthTable[year];
    if (yearData == null) return null;

    // 当年データから翌年の最初の月のJDを取得するため、翌年データも確認
    final nextYearData = _lunarMonthTable[year + 1];

    // 当年の全月のJDリストを構築
    final List<double> monthJDs = [];
    final List<int> monthNums = []; // 旧暦月番号(1-12)

    for (final entry in yearData) {
      final String monthStr = entry[0] as String;
      final int gy = entry[1] as int;
      final int gm = entry[2] as int;
      final int gd = entry[3] as int;
      final double monthJD = _toJulianDay(gy, gm, gd);
      
      // 閏月の場合、月番号文字列から数値を取得
      final int lunarMonthNum;
      if (monthStr.startsWith('L')) {
        lunarMonthNum = int.parse(monthStr.substring(1));
      } else {
        lunarMonthNum = int.parse(monthStr);
      }
      
      monthJDs.add(monthJD);
      monthNums.add(lunarMonthNum);
    }

    // 翌年の最初の月のJDも検索境界として追加
    double nextYearFirstJD;
    if (nextYearData != null && nextYearData.isNotEmpty) {
      final first = nextYearData[0];
      nextYearFirstJD = _toJulianDay(
        first[1] as int, first[2] as int, first[3] as int);
    } else {
      // テーブルにない場合は概算（翌年の春節は約354日後）
      nextYearFirstJD = monthJDs.last + 30;
    }

    // JDが属する月を検索
    for (int i = 0; i < monthJDs.length; i++) {
      final double start = monthJDs[i];
      final double end = (i < monthJDs.length - 1)
          ? monthJDs[i + 1]
          : nextYearFirstJD;

      if (jd >= start && jd < end) {
        final int lunarMonth = monthNums[i];
        final int lunarDay = (jd - start).floor() + 1;
        return [lunarMonth, lunarDay];
      }
    }

    return null;
  }
